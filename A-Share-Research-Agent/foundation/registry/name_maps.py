"""跨口径板块名称路由 — 让各源用自己的口径板块回答"东财口径名"的查询。

设计原则（与"口径不合并"一致）：
- 这是**名称路由**（找到该用哪个源内板块去取值），不是取值合并——
  值本身永远来自被路由到的源，evidence 保留该源的真实板块名/口径标注；
- 仅收录**高置信**映射（源板块语义明确覆盖目标口径的场景），宁可缺失不可错配；
- 未映射的板块名原样透传（多数与源内名称一致即直接命中），
  仍匹配不到 → 提取 EMPTY（诚实降级，绝不就近编配）；
- 映射在东财封锁期（2026-10）未能做值级交叉复核，东财恢复后需对照复核。

数据方向：东财行业口径名（registry 的 {sector} 缺省口径）→ 各源自有板块名。
一个源板块可覆盖多个东财行业（多对一，方向合法）；反之不允许一对多（会错配）。

用法::

    from foundation.registry.name_maps import mapped_sector

    mapped_sector("sina", "半导体")   # -> "电子器件"
    mapped_sector("sina", "钢铁行业")  # -> "钢铁行业"（未映射，原样透传）
"""
